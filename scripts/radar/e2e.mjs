import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import sharp from "sharp";
import { syntheticSign } from "./fixtures.mjs";

const root = process.env.RADAR_TEST_URL || "http://127.0.0.1:3166";
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(root)) throw new Error("Use apenas loopback para o teste.");
const base = root+"/api/admin/radar";
assert.equal((await fetch(base)).status,401);
const login = await fetch(root+"/api/admin/login",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({password:process.env.RADAR_TEST_PASSWORD || "radar-test-only"})});
assert.equal(login.status,200);
const cookie=login.headers.get("set-cookie")?.split(";")[0];
assert.ok(cookie);
async function send(url=base,init={}) {
  return fetch(url,{...init,headers:{Cookie:cookie,...init.headers}});
}
const data=async r=>{const res=await r;assert.ok(res.ok,`HTTP ${res.status}: ${await res.clone().text()}`);return res.json();};
assert.equal((await data(send())).sandbox,true,"Never exercise a real data store");
const batch=randomUUID();
const upload=(buffer)=>send(base,{method:"POST",headers:{"x-radar-batch":batch},body:buffer});
const patch=(payload)=>send(base,{method:"PATCH",headers:{"Content-Type":"application/json"},body:JSON.stringify(payload)});
assert.equal((await upload(Buffer.from("not an image"))).status,415);
assert.equal((await upload(Buffer.alloc(12_000_001))).status,413);
assert.equal((await send(base,{method:"POST",headers:{Origin:"https://example.invalid","x-radar-batch":batch},body:"x"})).status,403);
let first;
for(const format of [1,2]){
  const bytes=await syntheticSign(format);
  const {asset}=await data(upload(bytes));
  assert.equal(asset.batch,batch);
  assert.equal((await data(upload(bytes))).duplicate,true);
  const out=await data(patch({action:"extract",id:asset.id}));
  assert.equal(out.status,"review");
  const fields=Object.fromEntries(Object.entries(out.observations).map(([k,o])=>[k,o.value]));
  assert.equal(fields.area,format===1?"53.1":"260.32");
  assert.equal(fields.floors,"2");
  assert.equal(fields.expires,format===1?"2026-08-09":"2027-09-01");
  assert.ok(fields.author&&fields.supervisor);
  assert.equal(fields.author===fields.supervisor,format===2);
  assert.ok(!JSON.stringify(out).includes("111.222.333"));
  assert.equal((await patch({action:"save",id:asset.id,version:out.version,fields})).status,400);
  assert.equal((await patch({action:"save",id:asset.id,version:out.version-1,fields,confirmed:true})).status,409);
  const saved=await data(patch({action:"save",id:asset.id,version:out.version,fields,confirmed:true}));
  assert.equal(saved.duplicate,false);
  if(format===1) first={...saved,fields};
  assert.equal((await send(base+"?image="+asset.id)).status,200);
  assert.equal((await fetch(base+"?image="+asset.id)).status,401);
}
const another=await data(upload(await syntheticSign(1,"#f7f7f7")));
const out=await data(patch({action:"extract",id:another.asset.id}));
const linked=await data(patch({action:"save",id:another.asset.id,version:out.version,fields:first.fields,confirmed:true}));
assert.equal(linked.id,first.id);
assert.equal(linked.duplicate,true);
const empty=await sharp({create:{width:480,height:320,channels:3,background:"#ffffff"}}).png().toBuffer();
const noText=await data(upload(empty));
const read=await data(patch({action:"extract",id:noText.asset.id}));
assert.equal(Object.keys(read.observations).length,0);
const retried=await data(patch({action:"extract",id:noText.asset.id}));
assert.equal(retried.attempts,2);
const result=await data(send());
assert.equal(result.projects.length,2);
assert.equal(result.assets.length,4);
const exported=await send(base+"?format=csv");
assert.equal(exported.status,200);
const csv=await exported.text();
assert.match(csv,/53,1/);assert.match(csv,/01\/09\/2027/);assert.doesNotMatch(csv,/Pessoa Sintética|Rua Exemplo|111\.222\.333/);
assert.equal((await send(base+"?format=csv&columns=author")).status,400);
const research=root+"/api/admin/radar/research";
const action=(version,op,extra={})=>send(research,{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({id:first.id,version,action:op,...extra})});
assert.equal((await fetch(research+"?project="+first.id)).status,401);
let intel=await data(send(research+"?project="+first.id));
assert.equal((await action(intel.version,"draft")).status,409);
const source={kind:"affiliation",role:"author",result:"verified",url:"https://example.com/project",corroboration:"https://example.org/portfolio",note:"Evidências sintéticas."};
assert.equal((await action(intel.version,"check",{check:{...source,corroboration:""}})).status,400);
assert.equal((await action(intel.version,"check",{check:{...source,url:"javascript:alert(1)"}})).status,400);
